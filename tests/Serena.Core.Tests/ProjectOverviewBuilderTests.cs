// The generated project overview: facts from the index and inventory, laid out as markdown.

using FluentAssertions;
using Microsoft.Extensions.Logging.Abstractions;
using Serena.Core.Project;
using Serena.Lsp;
using Serena.Lsp.Caching;
using Serena.Lsp.Client;
using Serena.Lsp.Protocol.Types;
using LspRange = Serena.Lsp.Protocol.Types.Range;

namespace Serena.Core.Tests;

public sealed class ProjectOverviewBuilderTests : IDisposable
{
    private readonly string _root = Path.Combine(Path.GetTempPath(), "serena_overview_" + Guid.NewGuid().ToString("N"));

    public ProjectOverviewBuilderTests()
    {
        Directory.CreateDirectory(Path.Combine(_root, "src", "Modules", "Patients", "Patients.Api"));
        Directory.CreateDirectory(Path.Combine(_root, "src", "Modules", "Patients", "Patients.Tests"));
        Directory.CreateDirectory(Path.Combine(_root, "src", "Shared", "Shared.Types"));
    }

    [Fact]
    public void Build_ReportsStructureBuildDependenciesCodeShapeAndConfiguration_FromFactsOnly()
    {
        string api = Path.Combine(_root, "src/Modules/Patients/Patients.Api/Patients.Api.csproj").Replace('\\', '/');
        string tests = Path.Combine(_root, "src/Modules/Patients/Patients.Tests/Patients.Tests.csproj").Replace('\\', '/');
        string shared = Path.Combine(_root, "src/Shared/Shared.Types/Shared.Types.csproj").Replace('\\', '/');
        string settings = Path.Combine(_root, "src/Modules/Patients/Patients.Api/appsettings.json").Replace('\\', '/');
        var inventory = new List<InventoryEntry>
        {
            new(api, "property", "TargetFramework", "net10.0"),
            new(api, "package", "MediatR", "12.4.0"),
            new(api, "package", "CSharpFunctionalExtensions", "3.6.0"),
            new(api, "project", "Shared.Types", "../../../Shared/Shared.Types/Shared.Types.csproj"),
            new(tests, "property", "TargetFramework", "net10.0"),
            new(tests, "package", "xunit", "2.9.2"),
            new(tests, "package", "FluentAssertions", "7.0.0"),
            new(tests, "project", "Shared.Types", "../../../Shared/Shared.Types/Shared.Types.csproj"),
            new(tests, "project", "Patients.Api", "../Patients.Api/Patients.Api.csproj"),
            new(shared, "property", "TargetFramework", "net10.0"),
            new(shared, "package", "CSharpFunctionalExtensions", "3.6.0"),
            new(settings, "json", "Adapters:OnBase:Url", "https://example"),
            new(settings, "json", "Adapters:NilRead:Url", "https://example"),
            new(settings, "json", "Logging:LogLevel:Default", "Information"),
        };

        var cache = new SymbolCache<UnifiedSymbolInformation[]>(Path.Combine(_root, ".serena", "cache", "csharp"), "symbols.json", 2, NullLogger.Instance);
        string service = Path.Combine(_root, "src/Modules/Patients/Patients.Api/PatientService.cs");
        string error = Path.Combine(_root, "src/Shared/Shared.Types/ProblemError.cs");
        File.WriteAllText(service, "namespace Patients.Api.Services;\r\nclass PatientService { }\r\n");
        File.WriteAllText(error, "﻿namespace Shared.Types;\r\nrecord ProblemError { }\r\n");
        cache.Set(service, "fp1", [Namespace("Patients.Api.Services", Type("PatientService", SymbolKind.Class, 7))]);
        cache.Set(error, "fp2", [Namespace("Shared.Types", Type("ProblemError", SymbolKind.Class, 4), Type("IFailure", SymbolKind.Interface, 1))]);

        var inputs = new ProjectOverviewBuilder.Inputs(
            _root, "hhss",
            ["HHSS.sln", "src/Modules/Patients/Patients.Api/Patients.Api.csproj", "src/Modules/Patients/Patients.Api/Program.cs",
             "src/Modules/Patients/Patients.Tests/Patients.Tests.csproj", "src/Shared/Shared.Types/Shared.Types.csproj", ".editorconfig"],
            new Dictionary<Language, SymbolCache<UnifiedSymbolInformation[]>> { [Language.CSharp] = cache },
            inventory, "0.6.2", new DateTimeOffset(2026, 11, 8, 14, 0, 0, TimeSpan.Zero))
        {
            EditorConfig = "root = true\n[*.cs]\nend_of_line = crlf\ndotnet_diagnostic.IDE0005.severity = error\ndotnet_diagnostic.CA1062.severity = warning\n",
            FileConvention = "CRLF in 2 of 2 sampled files; UTF-8 BOM on 1 of 2",
        };

        string text = ProjectOverviewBuilder.Build(inputs);

        text.Should().StartWith("# hhss");
        text.Should().Contain("Generated by serena-dotnet 0.6.2");
        text.Should().Contain("Solutions: `HHSS.sln`");
        text.Should().Contain("Projects: 3 (2 source, 1 test).");
        text.Should().Contain("target frameworks net10.0 (3)");
        text.Should().Contain("- `src/Modules/Patients`: 2 (1 test): Patients.Api");
        text.Should().Contain("- `src/Shared/Shared.Types`: 1 (0 test): Shared.Types");
        text.Should().Contain("Entry points: `src/Modules/Patients/Patients.Api/Program.cs`.");
        text.Should().Contain("Build: `dotnet build HHSS.sln`.");
        text.Should().Contain("Test: `dotnet test HHSS.sln` (FluentAssertions 7.0.0, xunit 2.9.2); 1 test project(s).");
        text.Should().Contain("enforces as errors (.editorconfig): IDE0005.");
        text.Should().NotContain("CA1062", "a warning is not an error the build enforces");
        text.Should().Contain("Declared style: end_of_line = crlf.");
        text.Should().Contain("Measured source files: CRLF in 2 of 2 sampled files; UTF-8 BOM on 1 of 2.");
        text.Should().Contain("- Shared.Types: referenced by 2 projects");
        text.Should().Contain("## Code shape (csharp)");
        text.Should().Contain("2 indexed files: 2 classes, 1 interfaces.");
        text.Should().Contain("- Patients.Api: 1").And.Contain("- Shared.Types: 1");
        text.Should().Contain("- PatientService (7): `src/Modules/Patients/Patients.Api/PatientService.cs`");
        text.Should().Contain("- functional: CSharpFunctionalExtensions 3.6.0 (2)");
        text.Should().Contain("- messaging: MediatR 12.4.0 (1)");
        text.Should().Contain("- testing: FluentAssertions 7.0.0 (1), xunit 2.9.2 (1)");
        text.Should().Contain("3 key(s) in 1 JSON configuration file(s)");
        text.Should().Contain("Top-level sections (keys): Adapters (2), Logging (1).");
    }

    [Fact]
    public void MeasureFileConvention_CountsLineEndingsAndBoms()
    {
        File.WriteAllBytes(Path.Combine(_root, "a.cs"), "﻿class A { }\r\n"u8.ToArray().Prepend((byte)0xBF).Prepend((byte)0xBB).Prepend((byte)0xEF).ToArray());
        File.WriteAllText(Path.Combine(_root, "b.cs"), "class B { }\nclass C { }\n");

        string? convention = ProjectOverviewBuilder.MeasureFileConvention(_root, ["a.cs", "b.cs"]);

        convention.Should().Be("CRLF in 1 of 2 sampled files; UTF-8 BOM on 1 of 2");
    }

    [Fact]
    public void Write_SavesTheGeneratedMemory_InsideTheProject()
    {
        File.WriteAllText(Path.Combine(_root, "Demo.sln"), "");
        var project = new SerenaProject(_root, NullLogger<SerenaProject>.Instance);

        string path = ProjectOverviewBuilder.Write(
            project, new Dictionary<Language, SymbolCache<UnifiedSymbolInformation[]>>(), NullLoggerFactory.Instance);

        path.Should().Be(Path.Combine(_root, ".serena", "memories", "generated", "project-overview.md"));
        File.ReadAllText(path).Should().Contain("Solutions: `Demo.sln`");
        new MemoriesManager(project.SerenaDataFolder).ListProjectMemories().Should().Contain(ProjectOverviewBuilder.MemoryName);
    }

    public void Dispose()
    {
        try { Directory.Delete(_root, recursive: true); } catch { /* best effort */ }
    }

    private static UnifiedSymbolInformation Namespace(string name, params UnifiedSymbolInformation[] children) => new()
    {
        Name = name,
        Kind = SymbolKind.Namespace,
        BodyRange = new LspRange(new Position(0, 0), new Position(99, 0)),
        Children = [.. children],
    };

    private static UnifiedSymbolInformation Type(string name, SymbolKind kind, int members) => new()
    {
        Name = name,
        Kind = kind,
        BodyRange = new LspRange(new Position(1, 0), new Position(2, 0)),
        Children = [.. Enumerable.Range(0, members).Select(i => new UnifiedSymbolInformation
        {
            Name = $"Member{i}",
            Kind = SymbolKind.Method,
            BodyRange = new LspRange(new Position(1, 0), new Position(1, 1)),
        })],
    };
}
